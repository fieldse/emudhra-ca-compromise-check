"""generate_certdata.py: generate emudhra_check/certdata.py from the certificate rules.

Reads every PEM block in rules/certs/*.pem, joins each to its rules/iocs.csv row by SHA-256, and
writes one CertRecord per certificate with its label, role, DER, SubjectPublicKeyInfo content and
first base64 line. Fails when a block has no row, a row has no block, or a role is unknown.

Usage: python3 -I tools/generate_certdata.py [--rules DIR] [--out FILE]
"""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import sys
from pathlib import Path

BEGIN = "-----BEGIN CERTIFICATE-----"
END = "-----END CERTIFICATE-----"
PEM_LINE_CHARS = 64
AAA = "AAA Certificate Services"
ROLES = {
    "compromised TLS intermediate": "COMPROMISED_INTERMEDIATE",
    "compromised code signing intermediate": "COMPROMISED_INTERMEDIATE",
    "G3 root": "G3_ROOT",
    "cross-sign issuer root": "CROSS_SIGN_ISSUER_ROOT",
}
ROOT_LABELS = {
    "emSign ECC Root CA - G3": "emSign ECC Root CA - G3 (removed root)",
    "emSign Root TLS CA - G3": "emSign Root TLS CA - G3 (issuer of the compromised TLS CAs)",
    "emSign Root CS CA - G3": "emSign Root CS CA - G3 (issuer of the compromised code-signing CAs)",
}
HEADER = '''"""certdata.py: the known certificates, generated by tools/generate_certdata.py from rules/.

One CertRecord per certificate in rules/certs, sorted by SHA-256. Do not edit by hand: change
rules/ and run python3 -I tools/generate_certdata.py.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class CertRecord:
    label: str
    role: str
    sha256: bytes
    der: bytes
    spki_value: bytes
    pem_line: bytes


RECORDS: tuple[CertRecord, ...] = (
'''


class GenerateError(Exception):
    """The rules cannot be turned into certificate records."""


def tlv(der: bytes, pos: int) -> tuple[int, int, int]:
    """Return the tag, content start and end of the DER element at pos."""
    tag = der[pos]
    first = der[pos + 1]
    if first < 0x80:
        return tag, pos + 2, pos + 2 + first
    count = first & 0x7F
    length = int.from_bytes(der[pos + 2 : pos + 2 + count], "big")
    start = pos + 2 + count
    if start + length > len(der):
        raise GenerateError("DER element runs past the end")
    return tag, start, start + length


def spki_value(der: bytes) -> bytes:
    """Return the content octets of a certificate's SubjectPublicKeyInfo SEQUENCE."""
    _, cert_start, _ = tlv(der, 0)
    _, pos, _ = tlv(der, cert_start)
    tag, _, end = tlv(der, pos)
    if tag == 0xA0:
        pos = end
    for _ in range(5):
        _, _, pos = tlv(der, pos)
    tag, start, end = tlv(der, pos)
    if tag != 0x30:
        raise GenerateError("SubjectPublicKeyInfo is not a SEQUENCE")
    return der[start:end]


def pem_ders(text: str) -> list[bytes]:
    """Return the DER of every certificate block in a PEM file."""
    ders = []
    for chunk in text.split(BEGIN)[1:]:
        body, found, _ = chunk.partition(END)
        if not found:
            raise GenerateError("BEGIN CERTIFICATE without END")
        ders.append(base64.b64decode("".join(body.split()), validate=True))
    return ders


def label_for(row: dict[str, str]) -> str:
    """Return the output label of one IOC row."""
    name = row["name"]
    if row["role"] == "G3 root":
        return ROOT_LABELS[name]
    if row["role"] == "cross-sign issuer root":
        return name
    cross = ", Sectigo cross-sign" if row["issuer"] == AAA else ""
    return f"{name}{cross} (compromised key)"


def records(rules: Path) -> list[tuple[str, str, bytes, bytes, bytes, bytes]]:
    """Join the PEM blocks to the IOC rows and return one record tuple per certificate."""
    with open(rules / "iocs.csv", encoding="utf-8", newline="") as handle:
        rows = {row["sha256"].upper(): row for row in csv.DictReader(handle)}
    ders = {}
    for pem in sorted((rules / "certs").glob("*.pem")):
        for der in pem_ders(pem.read_text(encoding="utf-8")):
            ders[hashlib.sha256(der).hexdigest().upper()] = der
    if set(ders) - set(rows):
        raise GenerateError(
            f"certificate blocks with no iocs.csv row: {sorted(set(ders) - set(rows))}"
        )
    if set(rows) - set(ders):
        raise GenerateError(
            f"iocs.csv rows with no certificate block: {sorted(set(rows) - set(ders))}"
        )
    out = []
    for digest in sorted(ders):
        row = rows[digest]
        if row["role"] not in ROLES:
            raise GenerateError(f"unknown role: {row['role']}")
        der = ders[digest]
        pem_line = base64.b64encode(der)[:PEM_LINE_CHARS]
        out.append(
            (
                label_for(row),
                ROLES[row["role"]],
                bytes.fromhex(digest),
                der,
                spki_value(der),
                pem_line,
            )
        )
    return out


def render(rules: Path) -> str:
    """Return the text of certdata.py for the rules directory."""
    parts = [HEADER]
    for label, role, digest, der, spki, pem_line in records(rules):
        parts.append("    CertRecord(\n")
        parts.append(f"        label={label!r},\n")
        parts.append(f"        role={role!r},\n")
        for name, value in (
            ("sha256", digest),
            ("der", der),
            ("spki_value", spki),
            ("pem_line", pem_line),
        ):
            parts.append(f'        {name}=bytes.fromhex("{value.hex()}"),\n')
        parts.append("    ),\n")
    parts.append(")\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    """Parse the arguments and write certdata.py."""
    parser = argparse.ArgumentParser(
        description="Generate emudhra_check/certdata.py from rules/."
    )
    parser.add_argument(
        "--rules",
        type=Path,
        default=Path("rules"),
        help="rules directory (default: rules)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("emudhra_check/certdata.py"),
        help="module to write",
    )
    options = parser.parse_args(argv)
    try:
        text = render(options.rules)
    except (GenerateError, KeyError, ValueError, IndexError) as error:
        sys.stderr.write(f"generate_certdata.py: {error}\n")
        return 2
    options.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
