class TomlTest(unittest.TestCase):
    def assertQuick(self, start: float) -> None:
        self.assertLess(time.monotonic() - start, WATCHDOG)

    def test_cargo_lock_with_dependencies(self) -> None:
        found, complete = toml_package_versions(CARGO, "webpki-roots")
        self.assertTrue(complete)
        self.assertEqual(
            found,
            [
                LockPackage("0.26.11", ("webpki-roots 1.0.9",)),
                LockPackage("1.0.9", ("rustls-pki-types",)),
            ],
        )

    def test_uv_lock_skips_inline_tables(self) -> None:
        found, complete = toml_package_versions(UV_LOCK, "certifi")
        self.assertTrue(complete)
        self.assertEqual([p.version for p in found], ["2026.10.19"])
        self.assertEqual(package_count(UV_LOCK), 2)

    def test_poetry_lock_name_is_normalised(self) -> None:
        found, complete = toml_package_versions(POETRY, "certifi")
        self.assertTrue(complete)
        self.assertEqual([p.version for p in found], ["2026.7.22"])

    def test_crlf_and_bom(self) -> None:
        text = "﻿" + CARGO.replace("\n", "\r\n")
        found, complete = toml_package_versions(text, "webpki-roots")
        self.assertTrue(complete)
        self.assertEqual([p.version for p in found], ["0.26.11", "1.0.9"])
        self.assertEqual(found[0].dependencies, ("webpki-roots 1.0.9",))

    def test_name_without_version(self) -> None:
        text = '[[package]]\nname = "certifi"\n\n[[package]]\nname = "certifi"\nversion = "1.0"\n'
        self.assertEqual(
            toml_package_versions(text, "certifi")[0], [LockPackage("1.0", ())]
        )

    def test_duplicate_packages(self) -> None:
        text = '[[package]]\nname = "certifi"\nversion = "1"\n[[package]]\nname = "certifi"\nversion = "2"\n'
        self.assertEqual(
            [p.version for p in toml_package_versions(text, "certifi")[0]], ["1", "2"]
        )

    def test_multi_line_string_stops_the_read(self) -> None:
        for quote in ('"""', "'''"):
            with self.subTest(quote=quote):
                text = (
                    '[[package]]\nname = "certifi"\nversion = "2026.7.22"\n'
                    f"description = {quote}\nlong\n{quote}\n"
                    '[[package]]\nname = "certifi"\nversion = "2026.10.19"\n'
                )
                found, complete = toml_package_versions(text, "certifi")
                self.assertFalse(complete)
                self.assertEqual([p.version for p in found], ["2026.7.22"])

    def test_unterminated_string(self) -> None:
        text = '[[package]]\nname = "certifi"\nversion = "2026.7.22"\n[[package]]\nname = "cer'
        found, complete = toml_package_versions(text, "certifi")
        self.assertFalse(complete)
        self.assertEqual([p.version for p in found], ["2026.7.22"])

    def test_unterminated_array(self) -> None:
        text = (
            '[[package]]\nname = "x"\nversion = "1"\ndependencies = [\n "a",\n "b",\n'
        )
        self.assertFalse(toml_documents(text).complete)

    def test_deep_array(self) -> None:
        start = time.monotonic()
        text = (
            "a = "
            + "[" * 10000
            + "]" * 10000
            + '\n[[package]]\nname = "c"\nversion = "1"\n'
        )
        found, complete = toml_package_versions(text, "c")
        self.assertTrue(complete)
        self.assertEqual([p.version for p in found], ["1"])
        unbalanced = toml_documents("a = " + "[" * 10000)
        self.assertFalse(unbalanced.complete)
        self.assertQuick(start)

    def test_single_32_mib_line(self) -> None:
        start = time.monotonic()
        for text in (
            'x = "' + "a" * (32 << 20),
            "[" * (32 << 20),
            'x = ["a", ' * (1 << 18),
        ):
            self.assertFalse(toml_documents(text).complete)
        self.assertQuick(start)

    def test_million_digit_version(self) -> None:
        start = time.monotonic()
        text = (
            '[[package]]\nname = "webpki-roots"\nversion = "' + "9" * (1 << 20) + '"\n'
        )
        found, complete = toml_package_versions(text, "webpki-roots")
        self.assertTrue(complete)
        self.assertEqual(len(found[0].version), 1 << 20)
        self.assertQuick(start)

    def test_line_without_equals_marks_incomplete(self) -> None:
        result = toml_documents('[[package]]\nname = "a"\nnonsense\nversion = "1"\n')
        self.assertFalse(result.complete)
        self.assertEqual(result.tables[1].values, {"name": "a", "version": "1"})


class JsonTest(unittest.TestCase):
    def test_hook_turns_long_numbers_into_none(self) -> None:
        text = '{"v": 123456789012345678901234567890123}'
        self.assertEqual(bounded_json(text), {"v": None})
        self.assertIsInstance(json.loads(text)["v"], int)
        self.assertEqual(bounded_json('{"v": 1.5, "w": 12}'), {"v": 1.5, "w": 12})

    def test_malformed_and_deep(self) -> None:
        self.assertIsNone(bounded_json("{"))
        self.assertIsNone(bounded_json("[" * 100000 + "]" * 100000))


class RequirementsTest(unittest.TestCase):
    def test_pins(self) -> None:
        text = (
            "﻿# comment\r\n"
            "-r other.txt\r\n"
            'certifi==2026.7.22 ; python_version<"3.9"\r\n'
            "Certifi == 2026.10.18  # pinned\n"
            "certifi===2026.10.19\n"
            "certifi @ file:///tmp/certifi.whl\n"
            "certifi>=2026.10.18\n"
            "certifi[extra]==2026.1.1 --hash=sha256:00\n"
            "requests==2.32.3\n"
            "\n"
        )
        self.assertEqual(
            requirement_pins(text, "certifi"),
            ["2026.7.22", "2026.10.18", "2026.10.19", "2026.1.1"],
        )

    def test_empty_and_malformed(self) -> None:
        self.assertEqual(requirement_pins("", "certifi"), [])
        self.assertEqual(requirement_pins("certifi==\n==\n", "certifi"), [])

    def test_near_miss_line(self) -> None:
        start = time.monotonic()
        pins = requirement_pins("certifi==" * (4 << 20), "certifi")
        self.assertEqual(len(pins), 1)
        self.assertLess(time.monotonic() - start, WATCHDOG)

    def test_lines_split_on_every_line_break(self) -> None:
        self.assertEqual(requirement_pins("x\rcertifi==1.0\r", "certifi"), ["1.0"])


class PipfileTest(unittest.TestCase):
    def test_versions(self) -> None:
        text = json.dumps(
            {
                "_meta": {},
                "default": {"certifi": {"version": "==2026.7.22"}},
                "develop": {"Certifi": {"version": "==2026.10.19"}, "x": "y"},
            }
        )
        self.assertEqual(pipfile_versions(text, "certifi"), ["2026.7.22", "2026.10.19"])

    def test_unreadable(self) -> None:
        self.assertIsNone(pipfile_versions("not json", "certifi"))
        self.assertIsNone(pipfile_versions("[1]", "certifi"))
        self.assertEqual(pipfile_versions('{"default": []}', "certifi"), [])


class ComposerTest(unittest.TestCase):
    def test_versions(self) -> None:
        text = json.dumps(
            {
                "packages": [
                    {"name": "composer/ca-bundle", "version": "1.4.15"},
                    {"name": "x/y", "version": "1"},
                ],
                "packages-dev": [{"name": "composer/ca-bundle", "version": "v1.6.0"}],
            }
        )
        self.assertEqual(
            composer_versions(text, "composer/ca-bundle"), ["1.4.15", "1.6.0"]
        )

    def test_malformed_deep_and_digits(self) -> None:
        start = time.monotonic()
        self.assertIsNone(composer_versions("{", "composer/ca-bundle"))
        self.assertIsNone(
            composer_versions("[" * 1000 + "]" * 1000, "composer/ca-bundle")
        )
        digits = (
            '{"packages": [{"name": "composer/ca-bundle", "version": 1'
            + "0" * (8 << 20)
            + "}]}"
        )
        self.assertEqual(composer_versions(digits, "composer/ca-bundle"), [])
        self.assertLess(time.monotonic() - start, WATCHDOG)


class GemTest(unittest.TestCase):
    LOCK = (
        "GEM\n  remote: https://rubygems.org/\n  specs:\n    excon (1.7.3)\n      logger\n    logger (1.7.0)\n\n"
        "DEPENDENCIES\n  excon (~> 1.7)\n"
    )

    def test_lf_and_crlf(self) -> None:
        self.assertEqual(gem_versions(self.LOCK, "excon"), ["1.7.3"])
        self.assertEqual(
            gem_versions(self.LOCK.replace("\n", "\r\n"), "excon"), ["1.7.3"]
        )

    def test_near_miss_line(self) -> None:
        start = time.monotonic()
        self.assertEqual(gem_versions("excon (" * (4 << 20), "excon"), [])
        self.assertLess(time.monotonic() - start, WATCHDOG)


class MixTest(unittest.TestCase):
    def test_entries(self) -> None:
        text = (
            '%{\n  "castore": {:hex, :castore, "1.0.21", "e4", [:mix], [], "hexpm", "e4"},\r\n'
            '  "castore_fork": {:hex, :castore_fork, "1.0.1", "aa", [:mix], [], "hexpm", "aa"},\n'
            '  "certifi": {:hex, :certifi, "2.17.0", "81", [:rebar3], [], "hexpm", "81"},\n}\n'
        )
        self.assertEqual(
            mix_versions(text), [("castore", "1.0.21"), ("certifi", "2.17.0")]
        )

    def test_mismatched_and_near_miss(self) -> None:
        self.assertEqual(mix_versions('"castore": {:hex, :certifi, "1.0.0"'), [])
        start = time.monotonic()
        self.assertEqual(mix_versions('"castore": {:hex, :castore, "' * (1 << 20)), [])
        self.assertLess(time.monotonic() - start, WATCHDOG)


class NpmRangeTest(unittest.TestCase):
    def test_table(self) -> None:
        for spec, want in (
            ("^43.8.0", ("43.8.0", True)),
            ("~44.9.0", ("44.9.0", True)),
            ("44.9.1", ("44.9.1", True)),
            ("=44.9.1", ("44.9.1", True)),
            ("v44.9.1", ("44.9.1", True)),
            ("41.x", ("41.0.0", True)),
            ("41", ("41.0.0", True)),
            ("^45.0.0-beta.5", ("45.0.0-beta.5", True)),
            (">=43.0.0", ("43.0.0", False)),
            ("43.0.0 - 44.0.0", ("43.0.0", False)),
            ("^42.0.0 || ^43.0.0", ("42.0.0", False)),
            ("*", ("", False)),
            ("latest", ("", False)),
            ("<45", ("", False)),
            ("workspace:*", None),
            ("file:../electron", None),
            ("git+https://example.invalid/electron.git", None),
            ("github:electron/electron", None),
        ):
            with self.subTest(spec=spec):
                self.assertEqual(npm_range_lower_bound(spec), want)

    def test_near_miss(self) -> None:
        start = time.monotonic()
        self.assertEqual(
            npm_range_lower_bound('"electron": "' * (1 << 20)), ("", False)
        )
        self.assertIsNone(npm_exact_version("4" * (1 << 20)))
        self.assertLess(time.monotonic() - start, WATCHDOG)

    def test_exact(self) -> None:
        for spec, want in (
            ("43.8.0", "43.8.0"),
            ("=43.8.0", "43.8.0"),
            (" = 43.8.0 ", "43.8.0"),
            ("v43.8.0", "43.8.0"),
            ("45.0.0-beta.5", "45.0.0-beta.5"),
            ("43.8.0+build.1", "43.8.0+build.1"),
            ("^43.8.0", None),
            ("~43.8.0", None),
            ("43.x", None),
            ("43.8", None),
            ("43", None),
            (">=43.8.0", None),
            ("43.8.0 || 44.9.1", None),
            ("43.8.0 - 44.9.1", None),
            ("", None),
        ):
            with self.subTest(spec=spec):
                self.assertEqual(npm_exact_version(spec), want)


